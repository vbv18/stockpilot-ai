import os
import pandas as pd
import numpy as np
from pathlib import Path

def sanitize_latex(val):
    if pd.isna(val) or val is None or val == "" or str(val).lower() == "nan":
        return "--"
    s = str(val).replace("_", "\\_").replace("%", "\\%")
    return s

def format_num(val, decimals=2):
    if pd.isna(val) or val is None or val == "" or str(val).lower() == "nan":
        return "--"
    try:
        f = float(val)
        return f"{f:.{decimals}f}"
    except (ValueError, TypeError):
        return sanitize_latex(val)

def generate_tables(results_dir="experiments/results", output_dir="report/tables"):
    res_path = Path(results_dir)
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    
    # 1. Model Comparison Table (from btp_report or root)
    # We can provide a clean table for the BTP benchmark SKUs
    mc_file = res_path / "btp_report" / "model_comparison.csv"
    if not mc_file.exists():
        mc_file = res_path / "model_comparison.csv"
        
    if mc_file.exists():
        df_mc = pd.read_csv(mc_file)
        # Select key informative columns: SKU, Class, ADI, CV2, Chosen Model, MASE Impr, S.Naive MASE, AutoETS MASE, Croston MASE, Naive MASE
        lines = [
            "% Auto-generated by stats-service/experiments/make_latex_tables.py",
            "\\begin{table}[htbp]",
            "\\centering",
            "\\small",
            "\\caption{Out-of-sample forecast accuracy comparison across rolling backtest origins.}",
            "\\label{tab:model_comparison}",
            "\\begin{tabular}{llcccccccc}",
            "\\toprule",
            "\\textbf{SKU} & \\textbf{Class} & \\textbf{ADI} & \\textbf{$CV^2$} & \\textbf{Selected Model} & \\textbf{SN MASE} & \\textbf{ETS MASE} & \\textbf{SBA MASE} & \\textbf{Naive MASE} & \\textbf{Impr (\\%)} \\\\",
            "\\midrule"
        ]
        for _, row in df_mc.iterrows():
            sku = sanitize_latex(row.get('sku_id', ''))
            dclass = sanitize_latex(row.get('demand_class', '')).capitalize()
            adi = format_num(row.get('adi', ''), 2)
            cv2 = format_num(row.get('cv2', ''), 2)
            chosen = sanitize_latex(row.get('chosen_model', ''))
            sn_mase = format_num(row.get('seasonal_naive_mase', ''), 3)
            ets_mase = format_num(row.get('autoets_mase', ''), 3)
            sba_mase = format_num(row.get('croston_sba_mase', ''), 3)
            n_mase = format_num(row.get('naive_mase', ''), 3)
            impr = format_num(row.get('mase_improvement', ''), 2)
            lines.append(f"{sku} & {dclass} & {adi} & {cv2} & {chosen} & {sn_mase} & {ets_mase} & {sba_mase} & {n_mase} & +{impr}\\% \\\\")
        lines.extend([
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}"
        ])
        (out_path / "model_comparison.tex").write_text("\n".join(lines), encoding="utf-8")
        print("Generated model_comparison.tex")

    # 2. Baseline Improvement Table
    bi_file = res_path / "btp_report" / "baseline_improvement.csv"
    if not bi_file.exists():
        bi_file = res_path / "baseline_improvement.csv"
    if bi_file.exists():
        df_bi = pd.read_csv(bi_file)
        lines = [
            "% Auto-generated by stats-service/experiments/make_latex_tables.py",
            "\\begin{table}[htbp]",
            "\\centering",
            "\\caption{Percentage forecast metric improvement over Naive persistence baseline.}",
            "\\label{tab:baseline_improvement}",
            "\\begin{tabular}{llcccc}",
            "\\toprule",
            "\\textbf{SKU ID} & \\textbf{Selected Model} & \\textbf{MAE Impr (\\%)} & \\textbf{RMSE Impr (\\%)} & \\textbf{WAPE Impr (\\%)} & \\textbf{Coverage -- 0.80} \\\\",
            "\\midrule"
        ]
        for _, row in df_bi.iterrows():
            sku = sanitize_latex(row.get('sku_id', ''))
            chosen = sanitize_latex(row.get('chosen_model', ''))
            mae_p = format_num(row.get('mae_pct', ''), 2)
            rmse_p = format_num(row.get('rmse_pct', ''), 2)
            wape_p = format_num(row.get('wape_pct', ''), 2)
            cov_delta = format_num(row.get('coverage_minus_nominal', ''), 4)
            if sku == "OVERALL":
                lines.append("\\midrule")
                lines.append(f"\\textbf{{{sku}}} & \\textbf{{{chosen}}} & \\textbf{{{mae_p}\\%}} & \\textbf{{{rmse_p}\\%}} & \\textbf{{{wape_p}\\%}} & \\textbf{{{cov_delta}}} \\\\")
            else:
                lines.append(f"{sku} & {chosen} & {mae_p}\\% & {rmse_p}\\% & {wape_p}\\% & {cov_delta} \\\\")
        lines.extend([
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}"
        ])
        (out_path / "baseline_improvement.tex").write_text("\n".join(lines), encoding="utf-8")
        print("Generated baseline_improvement.tex")

    # 3. Policy Comparison Table (Simulation vs Actual Holdout)
    pc_file = res_path / "btp_report" / "policy_comparison.csv"
    if not pc_file.exists():
        pc_file = res_path / "policy_comparison.csv"
    if pc_file.exists():
        df_pc = pd.read_csv(pc_file)
        lines = [
            "% Auto-generated by stats-service/experiments/make_latex_tables.py",
            "\\begin{table}[htbp]",
            "\\centering",
            "\\footnotesize",
            "\\caption{Replenishment policy performance under 500 Monte Carlo simulation runs and 28-day historical replay.}",
            "\\label{tab:policy_comparison}",
            "\\begin{tabular}{llccccccc|cccc}",
            "\\toprule",
            " & & & & \\multicolumn{5}{c|}{\\textbf{Monte Carlo Simulation (500 runs)}} & \\multicolumn{4}{c}{\\textbf{Historical Replay (28 days)}} \\\\",
            "\\textbf{SKU} & \\textbf{Policy} & \\textbf{$Q$} & \\textbf{$s$} & \\textbf{Cost (\\rupee)} & \\textbf{Fill Rate} & \\textbf{CSL} & \\textbf{LTD Cal.} & \\textbf{Lost Units} & \\textbf{Cost (\\rupee)} & \\textbf{Fill Rate} & \\textbf{Stk. Days} & \\textbf{Lost Units} \\\\",
            "\\midrule"
        ]
        curr_sku = None
        for _, row in df_pc.iterrows():
            sku = str(row.get('sku_id', ''))
            if curr_sku is not None and sku != curr_sku:
                lines.append("\\midrule")
            curr_sku = sku
            
            pol_raw = str(row.get('policy', ''))
            if pol_raw == "deterministic":
                pol = "$s_{\\text{det}}$"
            elif pol_raw in ["uncertainty_aware", "empirical"]:
                pol = "$s_{\\text{emp}}$"
            else:
                pol = "$s_{\\text{quant}}$"
                
            q = format_num(row.get('eoq', ''), 0)
            s = format_num(row.get('rop', ''), 0)
            scost = format_num(row.get('sim_total_cost', ''), 2)
            sfr = format_num(row.get('sim_service_level', ''), 3)
            scsl = format_num(row.get('sim_csl', ''), 3)
            ltd = format_num(row.get('ltd_calibration', ''), 3)
            slost = format_num(row.get('sim_stockout_units', ''), 1)
            
            acost = format_num(row.get('actual_total_cost', ''), 2)
            afr = format_num(row.get('actual_service_level', ''), 3)
            astk_days = format_num(row.get('actual_stockout_days', ''), 0)
            alost = format_num(row.get('actual_stockout_units', ''), 1)
            
            lines.append(f"{sanitize_latex(sku)} & {pol} & {q} & {s} & {scost} & {sfr} & {scsl} & {ltd} & {slost} & {acost} & {afr} & {astk_days} & {alost} \\\\")
        lines.extend([
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}"
        ])
        (out_path / "policy_comparison.tex").write_text("\n".join(lines), encoding="utf-8")
        print("Generated policy_comparison.tex")

    # 4. Portfolio Cost Allocation Table
    pfc_file = res_path / "btp_report" / "portfolio_cost.csv"
    if not pfc_file.exists():
        pfc_file = res_path / "portfolio_cost.csv"
    if pfc_file.exists():
        df_pfc = pd.read_csv(pfc_file)
        lines = [
            "% Auto-generated by stats-service/experiments/make_latex_tables.py",
            "\\begin{table}[htbp]",
            "\\centering",
            "\\small",
            "\\caption{Portfolio allocation under working-capital budget limit ($B = \\text{\\rupee 13,206.29}$).}",
            "\\label{tab:portfolio_cost}",
            "\\begin{tabular}{lccccccrc}",
            "\\toprule",
            "\\textbf{SKU ID} & \\textbf{Unconstr. $\\alpha$} & \\textbf{Constr. $\\alpha$} & \\textbf{Unconstr. $s$} & \\textbf{Constr. $s$} & \\textbf{Unconstr. Inv.} & \\textbf{Constr. Inv.} & \\textbf{Cost Delta (\\rupee)} & \\textbf{Turnover} \\\\",
            "\\midrule"
        ]
